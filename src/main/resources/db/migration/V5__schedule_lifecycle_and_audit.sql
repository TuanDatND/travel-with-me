CREATE TABLE schedule_participant_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT NOT NULL REFERENCES event_participants(participant_id),
    registration_reference UUID NOT NULL,
    action VARCHAR(50) NOT NULL,
    old_status VARCHAR(30), new_status VARCHAR(30) NOT NULL,
    registered_price NUMERIC(18,2) NOT NULL,
    changed_by BIGINT, reason TEXT, changed_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_schedule_participant_history ON schedule_participant_history(participant_id, changed_at DESC);

CREATE TABLE schedule_payment_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT NOT NULL REFERENCES event_participants(participant_id),
    registration_reference UUID NOT NULL,
    transaction_id BIGINT,
    dedup_key VARCHAR(200) NOT NULL UNIQUE,
    kind VARCHAR(50) NOT NULL CHECK (kind IN ('REFUND_REVIEW','LATE_PAYMENT')),
    amount NUMERIC(18,2) NOT NULL,
    reason TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_schedule_payment_reviews_participant ON schedule_payment_reviews(participant_id, review_id);
